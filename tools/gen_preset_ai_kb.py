#!/usr/bin/env python3
"""Generate PresetAi/KnowledgeBase.generated.cs from preset-ai-ref/kb.py"""
import ast
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
KB = ROOT / "preset-ai-ref" / "kb.py"
OUT = ROOT / "PresetAi" / "KnowledgeBase.generated.cs"


def load_lists():
    tree = ast.parse(KB.read_text())
    games = gpus = None
    for node in tree.body:
        if isinstance(node, ast.Assign):
            for t in node.targets:
                if isinstance(t, ast.Name):
                    if t.id == "GAMES":
                        games = ast.literal_eval(node.value)
                    if t.id == "GPUS":
                        gpus = ast.literal_eval(node.value)
    if games is None or gpus is None:
        raise SystemExit("GAMES/GPUS not found in kb.py")
    return games, gpus


def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def main():
    games, gpus = load_lists()
    lines = [
        "// <auto-generated by tools/gen_preset_ai_kb.py — do not edit>",
        "namespace UniversalFrameFX.PresetAi;",
        "",
        "public static partial class KnowledgeBase",
        "{",
        "    public static readonly GameEntry[] Games =",
        "    {",
    ]
    for g in games:
        name, exe, aliases, cost, hud, comp, ac = g
        als = ", ".join(f'"{esc(a)}"' for a in aliases)
        lines.append(
            f'        new("{esc(name)}", "{esc(exe)}", new[] {{ {als} }}, {cost}, {1 if hud else 0} != 0, {1 if comp else 0} != 0, {1 if ac else 0} != 0),'
        )
    lines += [
        "    };",
        "",
        "    public static readonly GpuEntry[] Gpus =",
        "    {",
    ]
    for g in gpus:
        name, aliases, score, vendor, series = g
        als = ", ".join(f'"{esc(a)}"' for a in aliases)
        lines.append(
            f'        new("{esc(name)}", new[] {{ {als} }}, {score}, "{esc(vendor)}", "{esc(series)}"),'
        )
    lines += ["    };", "}", ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines))
    print("wrote", OUT, len(games), "games", len(gpus), "gpus")


if __name__ == "__main__":
    main()
