from assist import load_model; from chat import Chat
c=Chat(load_model("ckpt_r3.pt"))
T=["hi, can you help me?","what's the weather like tomorrow?","I want to play Cyberpunk 2077, getting about 45 fps and want 120",
   "actually I have a 4070","what about 4K","I hate blur and ghosting","make it quieter","turn frame gen off","switch to Valorant","start over"]
out=["# Preset assistant chat demo (10 turns, scripted)\n","Model: rules + r3 1M model hybrid (current default). Generated by chat_demo.py.\n"]
for t in T: out+= [f"**You:** {t}\n",f"**Assistant:** "+c.turn(t).replace("\n","  \n")+"\n"]
open("chat_demo.md","w").write("\n".join(out)); print("\n".join(out))
